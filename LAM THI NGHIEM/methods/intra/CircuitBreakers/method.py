"""
Circuit Breakers (RepE) - Improving Alignment and Robustness with Circuit Breakers
                          (intra, NeurIPS 2024) - GENERATION entry point.

Paper: https://arxiv.org/abs/2406.04313 | repo: GraySwanAI/circuit-breakers
Mechanism: instead of teaching the model to refuse, it BREAKS the internal representations
that lead to harmful output. LoRA is inserted into every linear layer of layers 0-20 and a
representation-rerouting (RepE) loss is applied at layers 10 and 20, so a harmful
continuation derails mid-generation rather than completing.

Training data (for reference; not needed to run this file):
  - circuit breaker set: harmful query+completion generated by an uncensored LLM,
    filtered against HarmBench (BLEU < 0.3)
  - retain set: UltraChat + XSTest (+ extra refusal data for Llama-3)
Reported cost: 150 steps, batch 16, 1x A100-80GB, ~20 minutes. alpha=10 for Llama-3.

INTRA method -> defense is in the weights, no inference overhead, hook = local_generate.

WARNING (must be stated in the report): the retain set contains XSTest, which is exactly
our over-refusal benchmark. The released checkpoint has therefore SEEN XSTest prompts, so
our XSTest number for this method is optimistically biased. Same issue as DeepRefusal.

Run (needs GPU):
  python method.py response --task all
  python method.py judge    --task xstest
  python method.py judge    --task harmbench
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, ROOT)

from core.runner import run_method                    # noqa: E402
from core.local_client import local_generate, resolve_model   # noqa: E402

# ----- Released checkpoint: Llama-3-8B-Instruct with circuit breakers (RR = representation rerouting) -----
CKPT = resolve_model("GraySwanAI/Llama-3-8B-Instruct-RR", env_var="CB_MODEL")
# Mistral variant: GraySwanAI/Mistral-7B-Instruct-RR
LORA = os.environ.get("CB_LORA") or None


if __name__ == "__main__":
    run_method(
        name="CircuitBreakers",
        slug="circuit_breakers",
        defense_type="intra",
        backend="local",
        model=CKPT,
        lora=LORA,
        generate=local_generate,
        out_dir=os.path.join(HERE, "outputs"),
    )
